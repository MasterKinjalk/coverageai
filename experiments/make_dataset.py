"""WP-10 dataset generator: nominal-physics samples from the simulator (mismatch "none").

Latin hypercube over Conditions (scenarios.random_conditions, 7-D) x uniformly random
catalog candidates (catalog.candidates()). Each row holds x, u, Derived, the five
outputs, plus a ``row_id``. Re-runnable: regenerate after any simulator change.

Usage: uv run python experiments/make_dataset.py [--n 50000] [--seed 20261018]
Writes data/datasets/v1.parquet (gitignored) and results/dataset_v1.md.
"""
from __future__ import annotations

import argparse
import dataclasses
import time

import numpy as np
import pandas as pd

from coverageai import catalog
from coverageai.config import ROOT, spec
from coverageai.contracts import Conditions, Derived, Setting
from coverageai.scenarios import random_conditions
from coverageai.simulator import SpraySimulator

X_COLS = [f.name for f in dataclasses.fields(Conditions)]
U_COLS = [f.name for f in dataclasses.fields(Setting)]
D_COLS = [f.name for f in dataclasses.fields(Derived)]
Y_COLS = ["coverage_pct", "deposition_ul_cm2", "drift_frac", "displacement_mm", "stains_per_cm2"]
VERSION = "v1"


def make_dataset(n: int = 50_000, seed: int = 20261018) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    xs = random_conditions(n, seed)
    cands = catalog.candidates()
    us = [cands[i] for i in rng.integers(0, len(cands), n)]
    ders = [catalog.derive(x, u) for x, u in zip(xs, us)]
    sim = SpraySimulator()
    out = sim.simulate_arrays(xs, us, np.random.default_rng([seed, 1]), "none", derived=ders)
    df = pd.DataFrame({
        **{c: [getattr(x, c) for x in xs] for c in X_COLS},
        **{c: [getattr(u, c) for u in us] for c in U_COLS},
        **{c: [getattr(d, c) for d in ders] for c in D_COLS},
        **{c: out[c] for c in Y_COLS},
    })
    df.insert(0, "row_id", np.arange(n))
    return df


def datasheet(df: pd.DataFrame, seed: int, secs: float, n_cand: int) -> str:
    L = [f"# Dataset {VERSION} datasheet", "",
         f"- Generated by `experiments/make_dataset.py`, seed {seed}, {len(df)} rows, "
         f"{secs:.1f} s. Regenerate after any simulator change; numbers below are for the "
         f"simulator as of generation time.",
         "- x: Latin hypercube (`scenarios.random_conditions`) over the spec operating ranges.",
         f"- u: uniform random draw from `catalog.candidates()` ({n_cand} settings, 5 psi grid).",
         "- Mismatch level: none (nominal physics; spread factor is still sampled iid per row, "
         "which is irreducible noise for any model).",
         f"- Schema version {spec()['schema_version']}; file `data/datasets/{VERSION}.parquet` (gitignored).",
         "", "## Input ranges", "", "| column | min | max | mean |", "|---|---|---|---|"]
    for c in X_COLS + ["pressure_psi"] + D_COLS:
        if df[c].dtype.kind in "fi":
            L.append(f"| {c} | {df[c].min():.3f} | {df[c].max():.3f} | {df[c].mean():.3f} |")
    L += ["", "## Categorical counts", ""]
    for c in ("family", "droplet_class"):
        L.append(f"- {c}: " + ", ".join(f"{k}={v}" for k, v in df[c].value_counts().sort_index().items()))
    L += ["", "## Output summaries", "",
          "| output | min | p10 | median | p90 | max | mean | std |", "|---|---|---|---|---|---|---|---|"]
    for c in Y_COLS:
        q = df[c].quantile([0.1, 0.5, 0.9])
        L.append(f"| {c} | {df[c].min():.3f} | {q[0.1]:.3f} | {q[0.5]:.3f} | {q[0.9]:.3f} | "
                 f"{df[c].max():.3f} | {df[c].mean():.3f} | {df[c].std():.3f} |")
    cc = spec()["coverage_classes"]
    cv = df["coverage_pct"]
    L += ["", "## Coverage classes", "",
          f"- acceptable (>= {cc['acceptable_min']}%): {(cv >= cc['acceptable_min']).mean():.1%}",
          f"- marginal: {((cv >= cc['marginal_min']) & (cv < cc['acceptable_min'])).mean():.1%}",
          f"- critical (< {cc['marginal_min']}%): {(cv < cc['marginal_min']).mean():.1%}",
          f"- drift_frac > 0.5: {(df['drift_frac'] > 0.5).mean():.1%}; "
          f"drift_frac == 1: {(df['drift_frac'] >= 1.0).mean():.1%}"]
    return "\n".join(L) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=50_000)
    ap.add_argument("--seed", type=int, default=20261018)
    a = ap.parse_args()
    t0 = time.perf_counter()
    df = make_dataset(a.n, a.seed)
    secs = time.perf_counter() - t0
    d = ROOT / "data" / "datasets"
    d.mkdir(parents=True, exist_ok=True)
    df.to_parquet(d / f"{VERSION}.parquet", index=False)
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / f"dataset_{VERSION}.md").write_text(
        datasheet(df, a.seed, secs, len(catalog.candidates())), encoding="utf8")
    print(f"wrote {len(df)} rows in {secs:.1f} s")


if __name__ == "__main__":
    main()
